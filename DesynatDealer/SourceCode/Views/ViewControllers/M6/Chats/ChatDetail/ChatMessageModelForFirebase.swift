import Foundation
import FirebaseFirestore
//import FirebaseFirestoreSwift

// Main message model for Firestore
struct ChatMessage: Codable, Identifiable {
    @DocumentID var id: String?             // Auto-generated by Firestore
    let by: String                          // "seller" / "buyer"
    let message: String                     // text OR image download URL
    let type: String                        // "0" = text, "1" = image
    let timestamp: Timestamp?
    let userId: Int?
    
    enum CodingKeys: String, CodingKey {
        case id
        case by
        case message
        case type
        case timestamp
        case userId = "user_id"
    }
}
